function dy = ImmunoEpiBoost(~,y,p)

%% parameters
N = p.N;%16;

alpha = p.alpha;	% susceptibility
beta = p.beta;      % infectivity
omega = p.omegaElement;	% waning
delta = p.delta;	% disease-induced mortality (=0)
gamma = p.gamma;	% recovery
A = p.A;            % contacts
%disp(p.B(1,4))
sigma = p.sigma;    % vaccination rate - first dose
sigma2 = p.sigma2;  % vaccination rate - second dose
sigmaB = p.sigmaB;  % vaccination rate - booster dose
mu = p.mu;          % natural death
tau = p.tau;        % aging
c = p.c;            % mixing

p1 = p.p1;          % infection fraction from S1 to I2,I3,I4
p2 = p.p2;          % infection fraction from S2 to I2,I3,I4
p3 = p.p3;          % infection fraction from S3 to I2,I3,I4

pax = (1 - p.pax);  % Protection from severe disease from Paxlovid
%need age structure

paxAgeIndex = [false false false false false false false false false false false false true true true true];

p1(:,paxAgeIndex) = [(1 - 1/2 * pax) .* p2(2, paxAgeIndex) + p2(1, paxAgeIndex);
      (1 - pax) .* p2(3, paxAgeIndex) + 1/2 * pax .* p2(2, paxAgeIndex);
      pax .* p2(3, paxAgeIndex)];  % Infection fraction from S1

p2(:,paxAgeIndex) = [(1 - 1/2 * pax) .* p2(2, paxAgeIndex) + p2(1, paxAgeIndex);
      (1 - pax) .* p2(3, paxAgeIndex) + 1/2 * pax .* p2(2, paxAgeIndex);
      pax .* p2(3, paxAgeIndex)];  % Infection fraction from S2

p3(:,paxAgeIndex) = [zeros(1, sum(paxAgeIndex));
      (1 - pax) .* p3(3, paxAgeIndex) + 1/2 * pax .* p3(2, paxAgeIndex);
      pax .* p3(3, paxAgeIndex)];  % Infection fraction from S3


p1(isnan(p1))=0;        % set NaN t0 0
p2(isnan(p2))=0;  
p3(isnan(p3))=0;


qq = (1-p.qq); % vaccine faliure in protecting from severe disease
% infection fraction from V1 to I6, I7, and I8
pv2 = [(1-1/2*qq).*p2(2,:)+p2(1,:);(1-qq).*p2(3,:)+1/2*qq.*p2(2,:);qq.*p2(3,:)]; 
% infection fraction from V2 to I6, I7, and I8
pv3 = [zeros(1,16);(1-qq).*p3(3,:)+1/2*qq.*p3(2,:);qq.*p3(3,:)];  

if p.qq_SLabel %Label for whether we apply the protection from severe disease to susceptible classes (1) or only to V1 compartments ( 0)
    pS2=pv2;
    pS3=pv3;
else
    pS2=p2;
    pS3=p3;
end

rho = p.rho; % vaccination efficacy
%epsilon = .6;
ep = (1-(p.epsilon));
      
%{
rho1 = p.rho1;      % vaccination fraction from S1
rho2 = p.rho3;      % vaccination fraction from S2
rho3 = p.rho3;      % vaccination fraction from S3
%}
f = p.f;            % fecundity
kappa = p.kappa;

%% unpack compartments
p.compatmentsize = [8 8 8 8 8 4 4 4];

% rename for readablity
cs = p.compatmentsize;

%% unpack compartments
S = reshape(y(1:N*cs(1)),cs(1),N);
E1 = reshape(y(cs(1)*N+1:sum(cs(1:2))*N),cs(2),N);
E2 = reshape(y(sum(cs(1:2))*N+1:sum(cs(1:3))*N),cs(3),N);
E3 = reshape(y(sum(cs(1:3))*N+1:sum(cs(1:4))*N),cs(4),N);
I = reshape(y(sum(cs(1:4))*N+1:sum(cs(1:5))*N),cs(5),N);

V1 = reshape(y(sum(cs(1:5))*N+1:sum(cs(1:6))*N),cs(6),N);
V2 = reshape(y(sum(cs(1:6))*N+1:sum(cs(1:7))*N),cs(7),N);
VB = reshape(y(sum(cs(1:7))*N+1:sum(cs(1:8))*N),cs(8),N);

Nt = sum(S + E1 + E2 + E3 + I) + sum(V1 + V2 + VB);

%% Vectorized threshold to set compartments to zero

S(S < p.threshold) = 0;
% E1(E1 < p.threshold) = 0;
% E2(E2 < p.threshold) = 0;
% E3(E3 < p.threshold) = 0;
% I(I < p.threshold) = 0;
% V1(V1 < p.threshold) = 0;
% V2(V2 < p.threshold) = 0;
% VB(VB < p.threshold) = 0;

%% initialize new time step

dS = NaN(cs(1),N);
dE1 = NaN(cs(2),N);
dE2 = NaN(cs(3),N);
dE3 = NaN(cs(4),N);
dI = NaN(cs(5),N);
dV1 = NaN(cs(6),N);
dV2 = NaN(cs(7),N);
dVB = NaN(cs(8),N);

% yellow = NaN(2,N);
% blue = NaN(3,N);
% red = NaN(3,N);

%% Birth
% Hethcote 1997 Equation 4.8
%%q = p.q;%q not used
birth = sum(f.*(sum(S)+sum(E1)+sum(E2)+sum(E3)+sum(I)+sum(V1)+sum(V2)+sum(VB)));

%% Infection

% Calculate total force of infection from both compartments (1:4 and 5:8)
Xm = sum((beta .* I(1:4, :))) + sum((beta .* I(5:8, :)));

% Normalize the force of infection by total population (Nt)
Ym = Xm ./ Nt;

% Calculate the effective force of infection (infect)
% Multiply normalized infection force (Ym) by the contact rate (c)
infect = c * Ym';

% Multiply the infection force by the susceptible-saturation factor if the label indicates so
if p.S_fLabel==0
    S_f=1;
else
    %S_f=((sum(S(:,:),'all')+sum(V1(:,:),'all')+sum(V2(:,:),'all')+sum(VB(:,:),'all'))/sum(Nt))^2;
    S_f=((sum(S(1:3,:),'all')+sum(S(5:7,:),'all')+sum(V1(1:2,:),'all'))/sum(Nt))^2;
end

infect= S_f * infect;

%% Equations
%The compartments numbering system includes the original S_1 to S_4 are
%labeled as S(i,:) i=1..4 and the S_i^v comparmets are labeled/indexed with
%S(i,:), i=5..8.

%% First age interval - Susceptible
    %Susceptible
dS(1,1) = birth - tau(1)*S(1,1) ...
            - sum(p1(:,1))*alpha(1,1)*A(1,1)*S(1,1)*infect(1) ...
            - mu(1)*S(1,1) ...
            + omega(2,1)*S(2,1) ...
            - sigma(1,1)*rho*S(1,1);        
dS(2,1) = - tau(1)*S(2,1) ...
            - sum(pS2(:,1))*alpha(2,1)*A(2,1)*S(2,1)*infect(1) ...
            - mu(1)*S(2,1) ...
            + omega(3,1)*S(3,1) - omega(2,1)*S(2,1) ...
            - sigma(2,1)*rho*S(2,1) + gamma(2,1)*I(2,1);        
dS(3,1) = - tau(1)*S(3,1) - sum(pS3(:,1))*alpha(3,1)*A(3,1)*S(3,1)*infect(1) ... 
            - mu(1)*S(3,1) + omega(4,1)*S(4,1) - omega(3,1)*S(3,1) ...
            - sigma(3,1)*rho*S(3,1) + gamma(3,1)*I(3,1);        
dS(4,1) = - tau(1)*S(4,1) ...
            - mu(1)*S(4,1) - omega(4,1)*S(4,1) ...
            - sigma(4,1)*rho*S(4,1) + gamma(4,1)*I(4,1);

    %Susceptible Vaccinated
dS(5,1) = - tau(1)*S(5,1) - sum(p1(:,1))*alpha(1,1)*A(1,1)*S(5,1)*infect(1) ...
            - mu(1)*S(5,1) - sigmaB(1,1)*rho*S(5,1) ...
            + omega(2,1)*S(6,1) + omega(1,1)*V1(1,1);        
dS(6,1) = - tau(1)*S(6,1) - sum(pS2(:,1))*alpha(2,1)*A(2,1)*S(6,1)*infect(1) ...
            - mu(1)*S(6,1) - omega(2,1)*S(6,1) ...
            - sigmaB(2,1)*rho*S(6,1) + gamma(2,1)*I(6,1)...
            + omega(3,1)*S(7,1) + omega(2,1)*V1(2,1);        
dS(7,1) = - tau(1)*S(7,1) - sum(pS3(:,1))*alpha(3,1)*A(3,1)*S(7,1)*infect(1) ... 
            - mu(1)*S(7,1) - omega(3,1)*S(7,1) ...
            - sigmaB(3,1)*rho*S(7,1) + gamma(3,1)*I(7,1)...
            + omega(4,1)*S(8,1)...
           + omega(3,1)*(...
            +V1(3,1)...
            +V1(4,1)...
            +V2(1,1)...
            +V2(2,1)...
            +V2(3,1)...
            +V2(4,1)...
            +VB(1,1)...
            +VB(2,1)...
            +VB(3,1)...
            +VB(4,1));
dS(8,1) = - tau(1)*S(8,1) ...
            - mu(1)*S(8,1) - omega(4,1)*S(8,1)...
            - sigmaB(4,1)*rho*S(8,1)...
            + gamma(4,1)*I(8,1);
%% First age interval - Vaccinated 1st dose
dV1(1,1) = - tau(1)*V1(1,1) - mu(1)*V1(1,1) ...
            + sigma(1,1)*rho*S(1,1) - sigma2(1,1)*V1(1,1)...
            - sum(pv2(:,1))*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1)...
            - omega(1,1)*V1(1,1);
dV1(2,1) = -tau(1)*V1(2,1) - mu(1)*V1(2,1)...
            + sigma(2,1)*rho*S(2,1) - sigma2(2,1)*V1(2,1)...
            - sum(pv3(:,1))*ep*alpha(3,1)*A(3,1)*V1(2,1)*infect(1)...
            - omega(2,1)*V1(2,1);
dV1(3,1) = -tau(1)*V1(3,1) - mu(1)*V1(3,1)...
            + sigma(3,1)*rho*S(3,1) - sigma2(3,1)*V1(3,1)...
            - omega(3,1)*V1(3,1);
dV1(4,1) = -tau(1)*V1(4,1) - mu(1)*V1(4,1)...
            + sigma(4,1)*rho*S(4,1) - sigma2(4,1)*V1(4,1)...
            - omega(3,1)*V1(4,1);
        
%% First age interval - Vaccinated 2nd dose
dV2(1,1) = -tau(1)*V2(1,1) - mu(1)*V2(1,1) + sigma2(1,1)*V1(1,1)...
            - omega(3,1)*V2(1,1);
dV2(2,1) = -tau(1)*V2(2,1) - mu(1)*V2(2,1) + sigma2(2,1)*V1(2,1)...
            - omega(3,1)*V2(2,1);
dV2(3,1) = -tau(1)*V2(3,1) - mu(1)*V2(3,1) + sigma2(3,1)*V1(3,1)...
            - omega(3,1)*V2(3,1);
dV2(4,1) = -tau(1)*V2(4,1) - mu(1)*V2(4,1) + sigma2(4,1)*V1(4,1)...
            - omega(3,1)*V2(4,1);
        
%% First age interval - Vaccinated Booster dose
dVB(1,1) =  -tau(1)*VB(1,1) - mu(1)*VB(1,1) ...
            + sigmaB(1,1)*rho*S(5,1)...
            ...%- sum(pv2(:,1))*ep*alpha(2,1)*A(2,1)*VB(1,1)*infect(1)...
            - omega(3,1)*VB(1,1);
dVB(2,1) = -tau(1)*VB(2,1) - mu(1)*VB(2,1)...
            + sigmaB(2,1)*rho*S(6,1)...
            ...%- sum(pv3(:,1))*ep*alpha(3,1)*A(3,1)*VB(2,1)*infect(1)...
            - omega(3,1)*VB(2,1);
dVB(3,1) = -tau(1)*VB(3,1) - mu(1)*VB(3,1)...
            + sigmaB(3,1)*rho*S(7,1)...
            - omega(3,1)*VB(3,1);
dVB(4,1) = -tau(1)*VB(4,1) - mu(1)*VB(4,1)...
            + sigmaB(4,1)*rho*S(8,1)...
            - omega(3,1)*VB(4,1);

%% First age interval - Exposed STAGE 1
    %Exposed
dE1(2,1) = - tau(1)*E1(2,1) ...
            + p1(1,1)*alpha(1,1)*A(1,1)*S(1,1)*infect(1) ...
            + p2(1,1)*alpha(2,1)*A(2,1)*S(2,1)*infect(1) ...
            - (mu(1)+kappa(2,1))*E1(2,1);
            %+ pv2(1,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
dE1(3,1) = - tau(1)*E1(3,1) ...
            + p1(2,1)*alpha(1,1)*A(1,1)*S(1,1)*infect(1) ...
            + p2(2,1)*alpha(2,1)*A(2,1)*S(2,1)*infect(1) ...
            + p3(2,1)*alpha(3,1)*A(3,1)*S(3,1)*infect(1) ...
            - (mu(1)+kappa(3,1))*E1(3,1);
            %+ pv2(2,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
            %+ pv3(2,1)*ep*alpha(3,1)*A(3,1)*V1(2,1)*infect(1) ...
dE1(4,1) = - tau(1)*E1(4,1) ...
            + p1(3,1)*alpha(1,1)*A(1,1)*S(1,1)*infect(1) ...
            + p2(3,1)*alpha(2,1)*A(2,1)*S(2,1)*infect(1) ...
            + p3(3,1)*alpha(3,1)*A(3,1)*S(3,1)*infect(1) ...
            - (mu(1)+kappa(4,1))*E1(4,1);
%             + pv2(3,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
%             + pv3(3,1)*ep*alpha(3,1)*A(3,1)*V1(2,1)*infect(1) ...
    %Exposed Vaccinated
dE1(6,1) = - tau(1)*E1(6,1) ...
            + p1(1,1)*alpha(1,1)*A(1,1)*S(5,1)*infect(1) ...
            + p2(1,1)*alpha(2,1)*A(2,1)*S(6,1)*infect(1) ...
            + pv2(1,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
            - (mu(1)+kappa(2,1))*E1(6,1);
dE1(7,1) = - tau(1)*E1(7,1) ...
            + p1(2,1)*alpha(1,1)*A(1,1)*S(5,1)*infect(1) ...
            + p2(2,1)*alpha(2,1)*A(2,1)*S(6,1)*infect(1) ...
            + p3(2,1)*alpha(3,1)*A(3,1)*S(7,1)*infect(1) ...
            + pv2(2,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
            + pv3(2,1)*ep*alpha(3,1)*A(3,1)*V1(2,1)*infect(1) ...
            - (mu(1)+kappa(3,1))*E1(7,1);
dE1(8,1) = - tau(1)*E1(8,1) ...
            + p1(3,1)*alpha(1,1)*A(1,1)*S(5,1)*infect(1) ...
            + p2(3,1)*alpha(2,1)*A(2,1)*S(6,1)*infect(1) ...
            + p3(3,1)*alpha(3,1)*A(3,1)*S(7,1)*infect(1) ...
            + pv2(3,1)*ep*alpha(2,1)*A(2,1)*V1(1,1)*infect(1) ...
            + pv3(3,1)*ep*alpha(3,1)*A(3,1)*V1(2,1)*infect(1) ...
            - (mu(1)+kappa(4,1))*E1(8,1);
%% First age interval - Exposed STAGE 2       
dE2(2,1) = - tau(1)*E2(2,1) + kappa(2,1)*E1(2,1) ...
            - (mu(1)+kappa(2,1))*E2(2,1);
dE2(3,1) = - tau(1)*E2(3,1) + kappa(3,1)*E1(3,1) ...
            - (mu(1)+kappa(3,1))*E2(3,1);
dE2(4,1) = - tau(1)*E2(4,1) + kappa(4,1)*E1(4,1) ...
            - (mu(1)+kappa(4,1))*E2(4,1);
        
dE2(6,1) = - tau(1)*E2(6,1) + kappa(2,1)*E1(6,1) ...
            - (mu(1)+kappa(2,1))*E2(6,1);
dE2(7,1) = - tau(1)*E2(7,1) + kappa(3,1)*E1(7,1) ...
            - (mu(1)+kappa(3,1))*E2(7,1);
dE2(8,1) = - tau(1)*E2(8,1) + kappa(4,1)*E1(8,1) ...
            - (mu(1)+kappa(4,1))*E2(8,1);

%% First age interval - Exposed STAGE 3        
dE3(2,1) = - tau(1)*E3(2,1) + kappa(2,1)*E2(2,1) ...
            - (mu(1)+kappa(2,1))*E3(2,1);
dE3(3,1) = - tau(1)*E3(3,1) + kappa(3,1)*E2(3,1) ...
            - (mu(1)+kappa(3,1))*E3(3,1);
dE3(4,1) = - tau(1)*E3(4,1) + kappa(4,1)*E2(4,1) ...
            - (mu(1)+kappa(4,1))*E3(4,1);
        
dE3(6,1) = - tau(1)*E3(6,1) + kappa(2,1)*E2(6,1) ...
            - (mu(1)+kappa(2,1))*E3(6,1);
dE3(7,1) = - tau(1)*E3(7,1) + kappa(3,1)*E2(7,1) ...
            - (mu(1)+kappa(3,1))*E3(7,1);
dE3(8,1) = - tau(1)*E3(8,1) + kappa(4,1)*E2(8,1) ...
            - (mu(1)+kappa(4,1))*E3(8,1);  
%% First age interval - Infected        
dI(2,1) = - tau(1)*I(2,1) + kappa(2,1)*E3(2,1) ...
            - (mu(1) + delta(2,1) + gamma(2,1))*I(2,1);
dI(3,1) = - tau(1)*I(3,1) + kappa(3,1)*E3(3,1)...
            - (mu(1) + delta(3,1) + gamma(3,1))*I(3,1);
dI(4,1) = - tau(1)*I(4,1) + kappa(4,1)*E3(4,1) ...
            - (mu(1) + delta(4,1) + gamma(4,1))*I(4,1);
        
dI(6,1) = - tau(1)*I(6,1) + kappa(2,1)*E3(6,1) ...
            - (mu(1) + delta(2,1) + gamma(2,1))*I(6,1);
dI(7,1) = - tau(1)*I(7,1) + kappa(3,1)*E3(7,1)...
            - (mu(1) + delta(3,1) + gamma(3,1))*I(7,1);
dI(8,1) = - tau(1)*I(8,1) + kappa(4,1)*E3(8,1) ...
            - (mu(1) + delta(4,1) + gamma(4,1))*I(8,1);

%%        
	
for n=2:N-1
%% Subsequent age intervals - Susceptible
    dS(1,n) = tau(n-1)*S(1,n-1) - tau(n)*S(1,n) ...
                - sum(p1(:,n))*alpha(1,n)*A(1,n)*S(1,n)*infect(n) ...
                - mu(n)*S(1,n) ...
                + omega(2,n)*S(2,n)...
                - sigma(1,n)*rho*S(1,n)...
                ;
    dS(2,n) = tau(n-1)*S(2,n-1) - tau(n)*S(2,n) ...
                - sum(pS2(:,n))*alpha(2,n)*A(2,n)*S(2,n)*infect(n) ...
                - mu(n)*S(2,n) + omega(3,n)*S(3,n) - omega(2,n)*S(2,n) - sigma(2,n)*rho*S(2,n)...
                + gamma(2,n)*I(2,n);
    dS(3,n) = tau(n-1)*S(3,n-1) - tau(n)*S(3,n) ...
                - sum(pS3(:,n))*alpha(3,n)*A(3,n)*S(3,n)*infect(n) ...
                - mu(n)*S(3,n) + omega(4,n)*S(4,n) - omega(3,n)*S(3,n) - sigma(3,n)*rho*S(3,n) ...
                + gamma(3,n)*I(3,n);
    dS(4,n) = tau(n-1)*S(4,n-1) - tau(n)*S(4,n) - sigma(4,n)*rho*S(4,n) ...
                - mu(n)*S(4,n) - omega(4,n)*S(4,n) + gamma(4,n)*I(4,n);
            
    dS(5,n) = tau(n-1)*S(5,n-1) - tau(n)*S(5,n) ...
                - sum(p1(:,n))*alpha(1,n)*A(1,n)*S(5,n)*infect(n) ...
                - mu(n)*S(5,n)...
                + omega(2,n)*S(6,n)...
                - sigmaB(1,n)*rho*S(5,n)...
                + omega(1,n)*V1(1,n);
    dS(6,n) = tau(n-1)*S(6,n-1) - tau(n)*S(6,n) ...
                - sum(pS2(:,n))*alpha(2,n)*A(2,n)*S(6,n)*infect(n) ...
                - mu(n)*S(6,n)...
                + omega(3,n)*S(7,n)...
                - omega(2,n)*S(6,n) - sigmaB(2,n)*rho*S(6,n)...
                + gamma(2,n)*I(6,n)...
                + omega(2,n)*V1(2,n);
    dS(7,n) = tau(n-1)*S(7,n-1) - tau(n)*S(7,n) ...
                - mu(n)*S(7,n)...
                - sigmaB(3,n)*rho*S(7,n) ...
                - sum(pS3(:,n))*alpha(3,n)*A(3,n)*S(7,n)*infect(n) ...
                - omega(3,n)*S(7,n)...
                + gamma(3,n)*I(7,n)...
                + omega(4,n)*S(8,n) ...
                + omega(3,n)*(...
                + V1(3,n)...
                + V1(4,n)...
                + V2(1,n)...
                + V2(2,n)...
                + V2(3,n)...
                + V2(4,n)...
                + VB(1,n)...
                + VB(2,n)...
                + VB(3,n)...
                + VB(4,n));
    dS(8,n) = tau(n-1)*S(8,n-1) - tau(n)*S(8,n) - sigmaB(4,n)*rho*S(8,n) ...
                - mu(n)*S(8,n) - omega(4,n)*S(8,n)...
                + gamma(4,n)*I(8,n);
                
%% Subsequent age interval - Vaccinated 1st dose
dV1(1,n) = tau(n-1)*V1(1,n-1) - tau(n)*V1(1,n) - mu(n)*V1(1,n) ...
            + sigma(1,n)*rho*S(1,n)...
            - sigma2(1,n)*V1(1,n)...
            - sum(pv2(:,n))*ep*alpha(2,n)*A(2,n)*V1(1,n)*infect(n)...
            - omega(1,n)*V1(1,n);
dV1(2,n) = tau(n-1)*V1(2,n-1) - tau(n)*V1(2,n) - mu(n)*V1(2,n)...
            + sigma(2,n)*rho*S(2,n) - sigma2(2,n)*V1(2,n)...
            - sum(pv3(:,n))*ep*alpha(3,n)*A(3,n)*V1(2,n)*infect(n)...
            - omega(2,n)*V1(2,n);
