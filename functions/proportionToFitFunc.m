function midDaily = proportionToFitFunc(fitProportions, solutionToFit,bothSim)

    % The proportionToFitFunc function takes in:
    % - fitProp: A structure containing the fit proportions for different compartments.
    % - solutionToFit: A 3D matrix containing the simulation model's results.
    % - bothSim: A logical vector indicating which time points should be considered.
    % It computes the weighted sum of different compartments, applying different
    % proportions (fitProportions) to their summed contributions across time.

    arguments
        fitProportions
        solutionToFit
        bothSim=0;
    end



%fitProportions = fitProp.fitProportions;%[0,0,0, 0.2];
if length(fitProportions)>length(solutionToFit)
    fitProportions=fitProportions(1:length(solutionToFit),:);
end
midDaily = fitProportions(:,1).*(...
    sum(solutionToFit(:,:,1),2)+sum(solutionToFit(:,:,5),2)...
    )+...
    fitProportions(:,2).*(...
    sum(solutionToFit(:,:,2),2)+sum(solutionToFit(:,:,6),2)...
    )+...
    fitProportions(:,3).*(...
    sum(solutionToFit(:,:,3),2)+sum(solutionToFit(:,:,7),2)...
    )+...
    fitProportions(:,4).*(...
    sum(solutionToFit(:,:,4),2)+sum(solutionToFit(:,:,8),2)...
    );
end