function  [tout, yout, deBug]=RunImmunoEpiFast_Boost(se,kval,simulateWindow,y_int)

%preset all slow load variables (faster, because some of the se's are gets)
vaccinate = se.vaccinate;
if se.sigmaLabel=="Calculate"
    maxcoverage = se.vaccineCoverage(:,1)';
    maxcoverageTwo = se.vaccineCoverage(:,2)';
    maxcoverageBoost = se.vaccineCoverage(:,3)';
    deltaCoverage = se.deltaCoverage;
    deltaCoverageBoost = se.deltaCoverageBoost;
end
mitagationWindowLengthShort = se.mitagationWindowLengthShort;
population = se.population;

startIndex = simulateWindow(1);

sigma=zeros(4,16,3); % initial vaccination rates for 4 immune states, 16 age groups and 3 doses


%set equation parameters to smaller datastructure p
p=setParamters(se,sigma);

%Time Breaks
timeBreaks = timeBreaksFunc(se.dateList(simulateWindow(1):simulateWindow(2),:));

%% ODE options
options = odeset('NonNegative',1:length(y_int));

%%Error check offset
os = 0;

%sigma (vaccination rate) error tracking
sigmaError = false;
se.sigmaError = sigmaError;

%%First Time Window
%p.Pop = population;
[c, A, ~] = GenerateContacts(se,1,kval);
p.c = c;
A = repmat(A',4,1);
p.A = A;

% % %omega
% % %waning of immunity (originally per year)
% % omega4 = se.omega4(1);
% % omega3 = se.omega3(1);
% % omega2 = se.omega2(1);
% % omega = ones(4,16);      
% % omega(1,:) = 0*omega(1,:);
% % omega(2,:) = omega2;%*omega(2,:);
% % omega(3,:) = omega3;%*omega(3,:);
% % omega(4,:) = omega4;%*omega(4,:);
% % p.omegaElement = omega/365; % adapts to per day

%startIndex = startIndex + 1;
% tspan = timeBreaks(1+os):(timeBreaks(2+os)+1);
% [tout,yout] = ode45(@ImmunoEpiBoost,tspan,y_int,options,p);


 tout = 0; %Time points generated by the simulation.
 yout = [y_int';y_int']; %State variable values at each time point.

%alocate for speed
% Preallocates arrays for storing time points (toutSave) and state variables (youtSave).
toutSave = Inf(timeBreaks(end),1);
youtSave = Inf(timeBreaks(end),length(y_int)); %1296 is length of yInit
% % 
outIndex = 1;
loopIndex = 0;
toutSave(1) = tout(1);
youtSave(1,:) = yout(1,:);


vacStep = sum(se.vaccinate(1:startIndex-1)); %Tracks how far the vaccination schedule has progressed.
deBug = []; %Placeholder for debugging information

%% loop start
for index = startIndex+os:(startIndex+length(timeBreaks)-2) %Iterates through each time window specified in timeBreaks
    loopIndex = loopIndex + 1;
    %% omega: waning of immunity (originally per year)
    
    omega = ones(4,16);   % 4 immune states and 16 age groups   
    omega(1,:) = se.omega(index);
    omega(2,:) = se.omega(index);
    omega(3,:) = se.omega(index);
    omega(4,:) = se.omega(index);
    if ~isempty(se.pax)
        p.pax = se.pax(index);
    else
        p.pax=0;
    end
    
    p.omegaElement = omega/365; % adapts to per day
    
    
    %if vaccinate(index) && vacStep<sum(vaccinate)-1 && 0 % debug remove 0
    %if vaccinate(index) && vacStep<length(maxcoverage)-1 
    
    if vaccinate(index) && vacStep<sum(vaccinate)-2
        vacStep = vacStep + 1;
              
        if se.sigmaLabel=="Calculate"
        %caculate vaccination rate sigma
        % if vacStep+1>112
        %     disp("error")
        % end
        [p.sigma,~] = sigmaCalculationAgeB(...
            vacStep,...
            p,...
            yout,...%youtSave,...
            se.newVacTarget,...
            mitagationWindowLengthShort,...
            maxcoverage, ...
            population);
        
        %caculate vaccination rate sigma2
        [p.sigma2,~] = sigmaCalculationTwoB(...
            vacStep,...
            p,...
            yout,...%youtSave,...
            mitagationWindowLengthShort,...
            maxcoverageTwo, ...
            population);
          
        [p.sigmaB,~] = sigmaCalculationBoostB(...
            vacStep,...
            p,...
            yout,...%youtSave,...
            se.newVacTarget,...
            maxcoverageBoost,...
            mitagationWindowLengthShort,...
            deltaCoverageBoost, ...%delta change
            population);

        %  if index > 200
        %      p.sigma = p.sigma*.0;
        %      p.sigma2 = p.sigma2*.0;
        %      p.sigmaB = p.sigmaB;
        % end

        elseif se.sigmaLabel=="Import"
            for i=1:4 %loop on immune states, giving them same sigmas
                sigma(i,:,1)=table2array(se.sigma1(vacStep,2:end));
                sigma(i,:,2)=table2array(se.sigma2(vacStep,2:end));
                sigma(i,:,3)=table2array(se.sigmaB(vacStep,2:end));
            end
            p.sigma=sigma(:,:,1);
            p.sigma2=sigma(:,:,2);
            p.sigmaB=sigma(:,:,3);
       end        
    end

        
    [c, A, ~,B] = GenerateContacts(se,index,kval);
    p.c = c;
    A = repmat(A',4,1);
    p.A = A;
    B = repmat(B',4,1);
    p.B = B;
    tspan = timeBreaks(loopIndex):(timeBreaks(loopIndex+1)+1);

    
    y_int = yout(end-1,:);
    
    if y_int <= se.threshold      
       y_int(y_int <= 10^-8)=0;  % force classes to zero if they get too small
    end                          % bc otherwise plotting function crashes
    
%          sz = size(y_int);  %forces all classes to zero
%         y_int = zeros(sz);  


   
   [tout,yout] = ode45(@ImmunoEpiBoost,tspan,y_int,options,p);

    
   toutSave(outIndex+1:outIndex + length(tout)-2) = tout(2:end-1);
   youtSave(outIndex+1:outIndex + length(tout)-2,:) = yout(2:end-1,:);

   outIndex = outIndex + length(tout)-2;
end
tout = toutSave;
yout = youtSave;

